# -*- coding: utf-8 -*-
"""Спецификации вариантов регистров (УПП / не-УПП).

Один и тот же регистр 1С в разных конфигурациях выгружается с разными
заголовками и немного разной структурой. Вместо двух почти одинаковых
классов-процессоров различия описываются данными: именами колонок и
флагами. Класс-процессор остаётся один, а тонкие наследники лишь
подставляют нужную спецификацию — этого требует фабрика, которая
сопоставляет выгрузку с процессором по имени класса.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class RegisterSpec:
    """Общая часть спецификации: чем находится шапка и как называется счёт."""

    header_word: str
    header_exact: str
    account_column: str
    indicator_column: str
    structure_message: str
    recognized_hint: str
    empty_message: str
